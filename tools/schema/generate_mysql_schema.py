"""Generates the MySQL schema of the .NET version from the reference (Python) data model, so both versions keep exactly
the same tables, columns, keys and rules.

    <python-backend>/.venv/Scripts/python tools/schema/generate_mysql_schema.py <python-backend-folder> <out.sql>

Type mapping (PostgreSQL → MySQL 8.4): UUID → CHAR(36), JSONB → JSON, TIMESTAMPTZ → DATETIME(6) (stored in UTC),
BOOLEAN → TINYINT(1), NUMERIC → DECIMAL, TEXT → TEXT. PostgreSQL-only features get MySQL equivalents:
products.search_vector (tsvector + trigram) → a FULLTEXT index on title, brand, description; the partial unique index
"one live delivery per package" → a virtual generated column with a unique index.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

backend = Path(sys.argv[1]).resolve()
out = Path(sys.argv[2])
sys.path.insert(0, str(backend))

from sqlalchemy import CHAR, JSON, Boolean, DateTime, DefaultClause, Text, text  # noqa: E402
from sqlalchemy.dialects import mysql  # noqa: E402
from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR, UUID  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

import app.models  # noqa: E402,F401
from app.db import Base  # noqa: E402

dialect = mysql.dialect()
meta = Base.metadata

# Columns: Postgres types → MySQL types
for t in meta.tables.values():
    for c in list(t.columns):
        if isinstance(c.type, UUID):
            c.type = CHAR(36)
        elif isinstance(c.type, JSONB):
            c.type = JSON()
        elif isinstance(c.type, DateTime):
            c.type = mysql.DATETIME(fsp=6)

# products.search_vector is PostgreSQL full-text; MySQL uses a FULLTEXT index instead (added below)
products = meta.tables["products"]
for ix in list(products.indexes):
    if ix.name in ("ix_products_search_vector", "ix_products_title_trgm"):
        products.indexes.discard(ix)
if "search_vector" in products.c:
    products._columns.remove(products.c.search_vector)

partial_active = None
da = meta.tables["delivery_assignments"]
for ix in list(da.indexes):
    if ix.name == "uq_delivery_assignments_active":
        partial_active = ix
        da.indexes.discard(ix)


def default_sql(col) -> str | None:
    sd = col.server_default
    if sd is None:
        return None
    arg = getattr(sd, "arg", None)
    txt = arg.text if hasattr(arg, "text") else str(arg)
    if txt.lower() in ("now()", "current_timestamp"):
        return "(UTC_TIMESTAMP(6))"
    if isinstance(col.type, JSON):
        return f"(CAST({txt if txt.startswith(chr(39)) else repr(txt)} AS JSON))"
    if isinstance(col.type, Boolean):
        return "1" if txt.lower() in ("true", "1", "'true'") else "0"
    if isinstance(arg, str) and not re.fullmatch(r"-?\d+(\.\d+)?", arg):
        lit = "'" + arg.replace("'", "''") + "'"  # a plain string default ("ai", "INR") is a literal
        return f"({lit})" if isinstance(col.type, Text) else lit  # TEXT defaults must be expressions in MySQL
    return f"({txt})" if isinstance(col.type, Text) else txt


lines = [
    "-- PixCart MySQL schema (generated by tools/schema/generate_mysql_schema.py from the reference data model).",
    "-- Do not edit by hand: change the model, regenerate, and add a new V###__*.sql script for existing databases.",
    "SET NAMES utf8mb4;",
    "SET FOREIGN_KEY_CHECKS = 0;",
    "",
]
for t in meta.sorted_tables:
    # server defaults in MySQL syntax (now() → UTC_TIMESTAMP(6), JSON literals as expressions, booleans as 1/0)
    for c in t.columns:
        d = default_sql(c)
        if d is not None:
            c.server_default = DefaultClause(text(d))
    ddl = str(CreateTable(t).compile(dialect=dialect)).strip()
    ddl = ddl.replace("BOOL", "TINYINT(1)")
    # CHECK rules are raw SQL: quote column names that are MySQL reserved words (condition, rank, ...)
    reserved = {c.name for c in t.columns if c.name.lower() in dialect.identifier_preparer.reserved_words}
    if reserved:
        def quote_checks(m):
            body = m.group(0)
            for name in reserved:
                body = re.sub(rf"(?<![`\w]){re.escape(name)}(?![`\w])", f"`{name}`", body)
            return body
        ddl = re.sub(r"CHECK \((?:[^()]|\([^()]*\))*\)", quote_checks, ddl)
    lines.append(ddl + " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;")
    for ix in sorted(t.indexes, key=lambda i: i.name or ""):
        lines.append(str(CreateIndex(ix).compile(dialect=dialect)).strip() + ";")
    lines.append("")

lines.append("-- product search (PostgreSQL tsvector + trigram in the reference version)")
lines.append("CREATE FULLTEXT INDEX ft_products_search ON products (title, brand, description);")
if partial_active is not None:
    lines.append("-- one live offer or trip per package at a time (a partial unique index in PostgreSQL)")
    lines.append("ALTER TABLE delivery_assignments ADD COLUMN active_sub_order_id CHAR(36) AS (CASE WHEN status IN "
                 "('offered','accepted','at_store','picked','on_the_way','reached') THEN sub_order_id END) VIRTUAL;")
    lines.append("CREATE UNIQUE INDEX uq_delivery_assignments_active ON delivery_assignments (active_sub_order_id);")
lines += ["", "SET FOREIGN_KEY_CHECKS = 1;", ""]
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines), encoding="utf-8")
print(f"{len(meta.sorted_tables)} tables -> {out}")
