"""Generates one C# model per table (PixCartAPI/Model/DomainModel/<Name>Model.cs) from the reference data model.

    <python-backend>/.venv/Scripts/python tools/schema/generate_models.py <python-backend-folder> <PixCartAPI/Model/DomainModel>

Columns are snake_case in MySQL and PascalCase in C#; Dapper maps them (DefaultTypeMap.MatchNamesWithUnderscores).
JSON columns are strings here (parse with JsonHelper where needed); UUIDs are Guid; timestamps are DateTime (UTC).
"""
from __future__ import annotations

import sys
from pathlib import Path

backend = Path(sys.argv[1]).resolve()
out = Path(sys.argv[2])
sys.path.insert(0, str(backend))

from sqlalchemy import BigInteger, Boolean, Date, DateTime, Integer, Numeric, SmallInteger, String, Text  # noqa: E402
from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR, UUID  # noqa: E402

import app.models  # noqa: E402,F401
from app.db import Base  # noqa: E402


def pascal(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.split("_") if p)


def singular(table: str) -> str:
    irregular = {"addresses": "address", "categories": "category", "deliveries": "delivery", "statuses": "status",
                 "inventory_levels": "inventory_level", "product_daily_stats": "product_daily_stat", "ad_stats": "ad_stat",
                 "push_tokens": "push_token", "refunds": "refund", "replies": "reply", "settings": "setting"}
    if table in irregular:
        return irregular[table]
    parts = table.split("_")
    last = parts[-1]
    if last.endswith("ies"):
        last = last[:-3] + "y"
    elif last.endswith("sses"):
        last = last[:-2]
    elif last.endswith("s") and not last.endswith("ss"):
        last = last[:-1]
    return "_".join(parts[:-1] + [last])


def cs_type(col) -> str | None:
    t = col.type
    nullable = col.nullable and not col.primary_key
    if isinstance(t, TSVECTOR):
        return None
    if isinstance(t, UUID):
        base = "Guid"
    elif isinstance(t, Boolean):
        base = "bool"
    elif isinstance(t, BigInteger):
        base = "long"
    elif isinstance(t, (SmallInteger, Integer)):
        base = "int"
    elif isinstance(t, Numeric):
        base = "decimal"
    elif isinstance(t, DateTime):
        base = "DateTime"
    elif isinstance(t, Date):
        base = "DateOnly"
    elif isinstance(t, JSONB):
        return "string?" if nullable else "string"
    elif isinstance(t, (String, Text)):
        return "string?" if nullable else "string"
    else:
        raise SystemExit(f"unmapped type {type(t).__name__} on {col.table.name}.{col.name}")
    return base + ("?" if nullable else "")


out.mkdir(parents=True, exist_ok=True)
names = []
for t in Base.metadata.sorted_tables:
    cls = pascal(singular(t.name)) + "Model"
    names.append((t.name, cls))
    props = []
    for c in t.columns:
        ty = cs_type(c)
        if ty is None:
            continue
        init = ' = "";' if ty == "string" else (' = "{}";' if False else "")
        if ty == "string" and str(c.type).upper().startswith("JSON"):
            init = ' = "null";'
        props.append(f"    /// <summary>{t.name}.{c.name}</summary>\n    public {ty} {pascal(c.name)} {{ get; set; }}{init}")
    body = "\n".join(props)
    (out / f"{cls}.cs").write_text(
        "// Generated by tools/schema/generate_models.py from the data model: one row of the table below. Do not edit by hand.\n"
        "namespace Model.DomainModel;\n\n"
        f"/// <summary>A row of the <c>{t.name}</c> table.</summary>\n"
        f"public partial class {cls}\n{{\n{body}\n}}\n",
        encoding="utf-8",
    )
(out / "Tables.cs").write_text(
    "// Generated: table names, so SQL in the DAL never misspells one.\nnamespace Model.DomainModel;\n\npublic static class Tables\n{\n"
    + "\n".join(f'    public const string {cls[:-5]} = "{name}";' for name, cls in names) + "\n}\n",
    encoding="utf-8",
)
print(len(names), "models ->", out)
