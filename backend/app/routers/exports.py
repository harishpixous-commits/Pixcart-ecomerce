"""Export endpoints for admins (by permission) and sellers (always limited to their own data).

``GET /api/admin/exports/{name}.{csv|xlsx|pdf}`` with optional filters:
``from``, ``to`` (IST dates), ``status``, ``month`` (TCS), ``seller``, ``category``, ``payment_method``,
``q`` (search), ``low_stock`` and ``columns`` (repeat the parameter once per column header).
"""
from __future__ import annotations

import csv
import io
import json
import re
import tempfile
import uuid
import zipfile
from datetime import date, datetime

from fastapi import APIRouter, Query
from fastapi.responses import Response, StreamingResponse
from pydantic import BaseModel, Field
from sqlalchemy import or_, select

from app.core.deps import AdminUser, CurrentUser, SellerAccount, SessionDep, audit, rate_limit
from app.core.errors import ApiError, Forbidden, NotFound
from app.core.permissions import load_roles, permissions_for
from app.models import Category, Seller
from app.services import exports
from app.services.cms import get_site
from app.services.reports import IST

router = APIRouter(tags=["exports"])

MEDIA = {"csv": "text/csv; charset=utf-8", "xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", "pdf": "application/pdf"}


def _headers(name: str) -> dict[str, str]:
    return {"Content-Disposition": f'attachment; filename="{name}"', "Cache-Control": "no-store", "X-Content-Type-Options": "nosniff"}


async def _names(session, extra: dict) -> dict[str, str]:
    out = {}
    if extra.get("seller"):
        out["seller"] = (await session.execute(select(Seller.display_name).where(Seller.id == extra["seller"]))).scalar_one_or_none() or ""
    if extra.get("category"):
        out["category"] = (await session.execute(select(Category.name).where(Category.id == extra["category"]))).scalar_one_or_none() or ""
    return out


async def _start(session, user, spec, fmt: str, *, seller_id, date_from, date_to, status, month, extra: dict, columns: list[str], who: str):
    if fmt not in exports.FORMATS:
        raise NotFound("Export format")
    try:
        ctx = exports.parse_context(spec, seller_id=seller_id, date_from=date_from, date_to=date_to, status=status, month=month, extra=extra)
        cols = exports.pick_columns(spec, columns, fmt)
    except ValueError as exc:
        raise ApiError(str(exc), "invalid_export_filter") from exc
    # Exports are heavy reads: a generous limit per person stops accidental loops and scraping.
    await rate_limit(session, f"export:{user.id}", limit=30, window_seconds=600)
    detail = json.dumps({"format": fmt, "from": str(date_from or ""), "to": str(date_to or ""), "status": status or "", "month": month or "",
                         "filters": {k: str(v) for k, v in ctx.extra.items()}, "columns": len(cols), "scope": who})
    audit(session, user, f"export.{spec.name}", "export", spec.name, detail)
    brand = (await get_site(session))["brand_name"]
    names = await _names(session, ctx.extra)
    await session.commit()
    name = exports.filename(brand, spec, ctx, fmt)
    if fmt == "csv":
        all_cols = None if len(cols) == len(spec.headers) else cols
        return StreamingResponse(exports.stream_csv(spec, ctx, all_cols), media_type=MEDIA["csv"], headers=_headers(name))
    about = exports.filter_summary(spec, ctx, names)
    title = f"{brand} — {spec.label}"
    if fmt == "xlsx":
        about = [("Export", spec.label), *about, ("Generated by", user.name or user.email or "")]
        f = await exports.build_xlsx(spec, ctx, cols, about, title)

        def chunks():
            try:
                while chunk := f.read(256 * 1024):
                    yield chunk
            finally:
                f.close()

        return StreamingResponse(chunks(), media_type=MEDIA["xlsx"], headers=_headers(name))
    pdf = await exports.build_pdf(spec, ctx, cols, about, title, brand)
    return Response(pdf, media_type=MEDIA["pdf"], headers=_headers(name))


def _extra(seller: uuid.UUID | None, category: uuid.UUID | None, payment_method: str | None, q: str | None, low_stock: int | None) -> dict:
    return {"seller": seller, "category": category, "payment_method": payment_method, "q": q, "low_stock": low_stock}


@router.get("/api/admin/exports")
async def admin_export_list(admin: AdminUser, session: SessionDep) -> dict:
    await load_roles(session)
    allowed = permissions_for(admin)
    return {"items": [exports.describe(s) for s in exports.ADMIN_EXPORTS.values() if s.permission in allowed], "max_days": exports.MAX_RANGE_DAYS}


@router.get("/api/admin/exports/lookup/{kind}")
async def admin_export_lookup(kind: str, admin: AdminUser, session: SessionDep, q: str = Query(default="", max_length=60)) -> dict:
    """Options for the seller and category filters."""
    await load_roles(session)
    if not permissions_for(admin) & {"orders", "reports", "payouts", "catalog", "sellers"}:
        raise Forbidden("Your role cannot use export filters")
    like = f"%{q.strip()}%"
    if kind == "seller":
        rows = (await session.execute(select(Seller.id, Seller.display_name).where(or_(Seller.display_name.ilike(like), Seller.legal_name.ilike(like))).order_by(Seller.display_name).limit(50))).all()
    elif kind == "category":
        rows = (await session.execute(select(Category.id, Category.name).where(Category.name.ilike(like)).order_by(Category.name).limit(50))).all()
    else:
        raise NotFound("Filter")
    return {"items": [{"value": str(i), "label": n} for i, n in rows]}


class BulkItem(BaseModel):
    name: str = Field(max_length=40)
    format: str = Field(default="csv", max_length=5)
    date_from: date | None = Field(default=None, alias="from")
    date_to: date | None = Field(default=None, alias="to")
    status: str | None = Field(default=None, max_length=30)
    month: str | None = Field(default=None, max_length=7)
    seller: uuid.UUID | None = None
    category: uuid.UUID | None = None
    payment_method: str | None = Field(default=None, max_length=10)
    q: str | None = Field(default=None, max_length=80)
    low_stock: int | None = Field(default=None, ge=0, le=100_000)
    columns: list[str] = Field(default_factory=list, max_length=60)

    model_config = {"populate_by_name": True}


class BulkIn(BaseModel):
    items: list[BulkItem] = Field(min_length=1, max_length=20)


async def _render(spec, fmt: str, ctx, cols: list[int], brand: str, user, names: dict) -> bytes:
    if fmt == "csv":
        chunks = [c async for c in exports.stream_csv(spec, ctx, None if len(cols) == len(spec.headers) else cols)]
        return b"".join(chunks)
    about = exports.filter_summary(spec, ctx, names)
    title = f"{brand} — {spec.label}"
    if fmt == "xlsx":
        f = await exports.build_xlsx(spec, ctx, cols, [("Export", spec.label), *about, ("Generated by", user.name or user.email or "")], title)
        try:
            return f.read()
        finally:
            f.close()
    return await exports.build_pdf(spec, ctx, cols, about, title, brand)


@router.post("/api/admin/exports/bulk")
async def admin_bulk_export(body: BulkIn, admin: AdminUser, session: SessionDep) -> Response:
    """Several exports in one ZIP, numbered in the order chosen, with a MANIFEST.csv of filters and row counts."""
    await load_roles(session)
    perms = permissions_for(admin)
    plans = []
    for n, item in enumerate(body.items, start=1):
        spec = exports.ADMIN_EXPORTS.get(item.name)
        if spec is None:
            raise NotFound(f"Export {item.name}")
        if spec.permission not in perms:
            raise Forbidden(f"Your role does not allow the {spec.label} export ({spec.permission})")
        if item.format not in exports.FORMATS:
            raise ApiError(f"{spec.label}: format must be csv, xlsx or pdf", "invalid_export_filter")
        try:
            ctx = exports.parse_context(spec, seller_id=None, date_from=item.date_from, date_to=item.date_to, status=item.status, month=item.month,
                                        extra=_extra(item.seller, item.category, item.payment_method, item.q, item.low_stock))
            cols = exports.pick_columns(spec, item.columns, item.format)
        except ValueError as exc:
            raise ApiError(f"{spec.label}: {exc}", "invalid_export_filter") from exc
        plans.append((n, spec, item.format, ctx, cols))
    await rate_limit(session, f"export:{admin.id}", limit=30, window_seconds=600)
    audit(session, admin, "export.bulk", "export", "bulk", json.dumps([f"{s.name}.{f}" for _, s, f, _, _ in plans]))
    brand = (await get_site(session))["brand_name"]
    await session.commit()
    buf = tempfile.SpooledTemporaryFile(max_size=32 * 1024 * 1024)
    manifest = io.StringIO()
    mw = csv.writer(manifest, lineterminator="\r\n")
    mw.writerow(["#", "File", "Export", "Format", "Filters"])
    width = len(str(len(plans)))
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for n, spec, fmt, ctx, cols in plans:
            names = await _names(session, ctx.extra)
            data = await _render(spec, fmt, ctx, cols, brand, admin, names)
            fname = f"{str(n).zfill(width)}-{exports.filename(brand, spec, ctx, fmt)}"
            zf.writestr(fname, data)
            mw.writerow([n, fname, spec.label, fmt.upper(), "; ".join(f"{k}: {v}" for k, v in exports.filter_summary(spec, ctx, names))])
        zf.writestr("MANIFEST.csv", "\ufeff" + manifest.getvalue())
    buf.seek(0)
    slug = re.sub(r"[^a-z0-9]+", "-", brand.lower()).strip("-") or "export"
    name = f"{slug}-reports-{datetime.now(IST):%Y-%m-%d-%H%M}.zip"

    def chunks():
        try:
            while chunk := buf.read(256 * 1024):
                yield chunk
        finally:
            buf.close()

    return StreamingResponse(chunks(), media_type="application/zip", headers=_headers(name))


@router.get("/api/admin/exports/{name}.{fmt}")
async def admin_export(
    name: str,
    fmt: str,
    admin: AdminUser,
    session: SessionDep,
    date_from: date | None = Query(default=None, alias="from"),
    date_to: date | None = Query(default=None, alias="to"),
    status: str | None = Query(default=None, max_length=30),
    month: str | None = Query(default=None, max_length=7),
    seller: uuid.UUID | None = None,
    category: uuid.UUID | None = None,
    payment_method: str | None = Query(default=None, max_length=10),
    q: str | None = Query(default=None, max_length=80),
    low_stock: int | None = Query(default=None, ge=0, le=100_000),
    columns: list[str] = Query(default=[], max_length=60),
) -> Response:
    spec = exports.ADMIN_EXPORTS.get(name)
    if spec is None:
        raise NotFound("Export")
    await load_roles(session)
    if spec.permission not in permissions_for(admin):
        raise Forbidden(f"Your role does not allow this export ({spec.permission})")
    return await _start(session, admin, spec, fmt, seller_id=None, date_from=date_from, date_to=date_to, status=status, month=month,
                        extra=_extra(seller, category, payment_method, q, low_stock), columns=columns, who="admin")


