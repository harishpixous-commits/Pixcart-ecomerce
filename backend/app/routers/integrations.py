"""Admin → Integrations: connect payment, SMS, email, WhatsApp, shipping, AI, monitoring and analytics.

Saving asks for the admin's password again (and the authenticator code when two-step sign-in is on),
because these keys move money and reach customers. Values are encrypted; responses never contain them.
"""
from __future__ import annotations

from typing import Any

from fastapi import APIRouter
from pydantic import BaseModel, Field
from sqlalchemy import delete

from app.config import settings
from app.core.deps import SessionDep, audit, rate_limit
from app.core.errors import ApiError
from app.core.permissions import Perm
from app.core.step_up import confirm_identity
from app.integrations import checks, runtime, store
from app.integrations.registry import BY_KEY, GROUP_LABELS
from app.models import IntegrationToken
from app.services.cms import get_site

router = APIRouter(prefix="/api/admin/integrations", tags=["integrations"])


def _infrastructure() -> list[dict[str, Any]]:
    """Set by Terraform on the servers, not in the admin panel; shown so the checklist is complete."""
    https = settings.public_web_url.startswith("https://")
    return [
        {"key": "domain", "name": "Domain and HTTPS", "ready": https, "detail": settings.public_web_url,
         "how": "Terraform: domain_name, Route 53 zone and the ACM certificate (docs/GO_LIVE.md step 3)."},
        {"key": "storage", "name": "Cloud storage for images and KYC files", "ready": settings.storage_backend == "s3",
         "detail": "Amazon S3" if settings.storage_backend == "s3" else "Local disk (development only)",
         "how": "Terraform creates the S3 buckets and sets STORAGE_BACKEND=s3."},
        {"key": "secrets", "name": "Server secrets (JWT, encryption key, database)", "ready": settings.environment != "production" or not settings.jwt_secret.startswith("dev-only"),
         "detail": "Generated by Terraform in AWS Secrets Manager", "how": "Nothing to do; Terraform generates them."},
    ]


@router.get("")
async def list_integrations(admin: Perm("integrations"), session: SessionDep) -> dict:
    items = await store.status(session)
    return {"environment": settings.environment, "groups": GROUP_LABELS, "items": items, "infrastructure": _infrastructure()}


class SaveIn(BaseModel):
    values: dict[str, Any] = Field(default_factory=dict)
    clear: list[str] = Field(default_factory=list, max_length=20)
    enabled: bool | None = None
    password: str = Field(min_length=1, max_length=200)
    totp: str = Field(default="", max_length=8)


@router.put("/{key}")
async def save_integration(key: str, body: SaveIn, admin: Perm("integrations"), session: SessionDep) -> dict:
    if key not in BY_KEY:
        raise ApiError("Unknown integration", "not_found", 404)
    await confirm_identity(session, admin, body.password, body.totp, purpose="integrations-save")
    try:
        changed = await store.save(session, key, values=body.values, clear=body.clear, enabled=body.enabled, actor_name=admin.name or admin.email or "")
    except store.IntegrationError as exc:
        raise ApiError(str(exc), "invalid_integration") from None
    # Field names only; values (and secrets) never reach the audit log.
    audit(session, admin, "integration.update", "integration", key, ", ".join(changed) or "no change")
    if key == "shiprocket" and changed:
        await session.execute(delete(IntegrationToken).where(IntegrationToken.provider == "shiprocket"))  # log in again with the new user
    await session.commit()
    if key == "sentry":
        runtime.apply_sentry(await store.get(session))
    items = await store.status(session)
    return {"changed": changed, "item": next(i for i in items if i["key"] == key)}


class TestIn(BaseModel):
    phone: str = Field(default="", pattern=r"^([6-9][0-9]{9})?$")
    to: str = Field(default="", max_length=200)


@router.post("/{key}/test")
async def test_integration(key: str, body: TestIn, admin: Perm("integrations"), session: SessionDep) -> dict:
    if key not in BY_KEY:
        raise ApiError("Unknown integration", "not_found", 404)
    await rate_limit(session, f"integrations-test:{admin.id}", limit=20, window_seconds=600)
    cfg = await store.get(session)
    params: dict[str, Any] = {"phone": body.phone}
    if key == "email":
        params |= {"to": body.to or admin.email or "", "brand": (await get_site(session))["brand_name"]}
    if key == "ai":
        from app.ai.settings import get_ai_settings

        params["model"] = (await get_ai_settings(session))["model"]
    result = await checks.run(key, cfg, **params)
    last = await store.record_test(session, key, result.ok, result.message)
    audit(session, admin, "integration.test", "integration", key, "ok" if result.ok else "failed")
    await session.commit()
    return last
