"""Every assistant reply (or a whole chat) as a file: PDF, Excel, CSV, Markdown or JSON.

Built from the saved blocks — the same figures that were on screen — never regenerated by the model.
"""
from __future__ import annotations

import csv
import io
import json
from datetime import datetime
from typing import Any

from app.services import docgen
from app.services.reports import IST

FORMATS = {"pdf": "application/pdf", "xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
           "csv": "text/csv; charset=utf-8", "md": "text/markdown; charset=utf-8", "json": "application/json"}


def _tables(blocks: list[dict[str, Any]]) -> list[tuple[str, list[str], list[list[Any]]]]:
    out = []
    for b in blocks:
        if b.get("type") == "table":
            out.append((b.get("title") or "Table", b["columns"], b["rows"]))
        elif b.get("type") == "metrics":
            out.append((b.get("title") or "Figures", ["Measure", "Value", "Note"], [[i["label"], i["value"], i.get("hint", "")] for i in b["items"]]))
        elif b.get("type") == "chart":
            cols = [b.get("title", "Label")] + [s["name"] for s in b["series"]]
            out.append((b.get("title") or "Chart data", cols, [[lbl] + [s["values"][i] if i < len(s["values"]) else "" for s in b["series"]] for i, lbl in enumerate(b["labels"])]))
    return out


def _esc(v: Any) -> str:
    return str(v).replace("|", "\\|").replace("\n", " ")


def _md_table(cols: list[str], rows: list[list[Any]]) -> str:
    esc = _esc
    lines = ["| " + " | ".join(esc(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def markdown(messages: list[dict[str, Any]], title: str) -> str:
    parts = [f"# {title}", f"_Exported {datetime.now(IST):%d %b %Y, %I:%M %p} IST_", ""]
    for m in messages:
        parts.append(f"## {'You' if m['role'] == 'user' else 'Assistant'}")
        if m["role"] == "user":
            parts.append(m.get("text", ""))
        for b in m.get("blocks") or []:
            t = b.get("type")
            if t == "text":
                parts.append(b["text"])
            elif t in ("table", "metrics", "chart"):
                for name, cols, rows in _tables([b]):
                    parts += [f"**{name}**", "", _md_table(cols, rows), ""]
            elif t == "file":
                parts.append(f"Download: {b.get('title')} ({str(b.get('format', '')).upper()})")
            elif t == "action":
                parts.append(f"Action: {b.get('summary')} — {b.get('status')}")
            elif t == "error":
                parts.append(f"> {b.get('text')}")
        parts.append("")
    return "\n".join(parts)


def build(fmt: str, messages: list[dict[str, Any]], title: str, brand: str) -> bytes:
    blocks = [b for m in messages for b in (m.get("blocks") or [])]
    if fmt == "json":
        return json.dumps({"title": title, "messages": messages}, ensure_ascii=False, indent=1, default=str).encode()
    if fmt == "md":
        return markdown(messages, title).encode()
    tables = _tables(blocks)
    if fmt == "csv":
        buf = io.StringIO()
        w = csv.writer(buf, lineterminator="\r\n")
        if not tables:
            w.writerow(["Text"])
            for b in blocks:
                if b.get("type") == "text":
                    w.writerow([b["text"]])
        for i, (name, cols, rows) in enumerate(tables):
            if i:
                w.writerow([])
            if len(tables) > 1:
                w.writerow([name])
            w.writerow(cols)
            for r in rows:
                w.writerow([("'" + str(c)) if str(c)[:1] in ("=", "+", "@") or (str(c)[:1] == "-" and not str(c)[1:2].isdigit()) else c for c in r])
        return b"\xef\xbb\xbf" + buf.getvalue().encode()
    if fmt == "xlsx":
        sheets = list(tables)
        texts = [b["text"] for b in blocks if b.get("type") == "text"]
        if texts:
            sheets.append(("Answer", ["Text"], [[t] for t in texts]))
        return docgen.xlsx_bytes(sheets, about=[("Title", title), ("Exported", datetime.now(IST).strftime("%d %b %Y %H:%M IST"))], about_title=brand)
    doc = docgen.PdfDoc(title, f"Exported {datetime.now(IST):%d %b %Y, %I:%M %p} IST")
    for m in messages:
        if m["role"] == "user":
            doc.heading("Question")
            doc.text(m.get("text", ""))
            continue
        doc.heading("Answer")
        for b in m.get("blocks") or []:
            t = b.get("type")
            if t == "text":
                doc.text(b["text"])
            elif t == "metrics":
                if b.get("title"):
                    doc.heading(b["title"])
                doc.metrics([(i["label"], i["value"]) for i in b["items"]])
            elif t == "table":
                if b.get("title"):
                    doc.heading(b["title"])
                doc.table(b["columns"], b["rows"], total_rows=b.get("total_rows"))
            elif t == "chart":
                doc.heading(b.get("title", "Chart"))
                doc.chart(b.get("kind", "bar"), b["labels"], [(s["name"], s["values"]) for s in b["series"]])
            elif t == "file":
                doc.note(f"Download offered: {b.get('title')} ({str(b.get('format', '')).upper()}) — {b.get('detail', '')}")
            elif t == "action":
                doc.note(f"Action: {b.get('summary')} — {b.get('status')}")
            elif t == "error":
                doc.note(b.get("text", ""))
    return docgen.pdf_bytes(doc, brand=brand)
